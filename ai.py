"""Разбор свободного текста в действия с задачами (Claude) и распознавание голоса (Groq Whisper)."""
from datetime import datetime, timedelta

import httpx
from anthropic import AsyncAnthropic

WEEKDAYS = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]

TOOL = {
    "name": "apply_actions",
    "description": "Применить действия к списку задач пользователя.",
    "input_schema": {
        "type": "object",
        "properties": {
            "actions": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "type": {"type": "string", "enum": ["add", "complete", "edit", "delete", "list", "delegate"]},
                        "task_id": {"type": "integer", "description": "Для complete/edit/delete: id существующей задачи"},
                        "title": {"type": "string", "description": "Короткая формулировка задачи, с глагола, без даты и времени"},
                        "area": {"type": "string", "description": "Одна из сфер пользователя"},
                        "due_date": {"type": "string", "description": "YYYY-MM-DD или пустая строка, если срока нет"},
                        "time": {"type": "string", "description": "HH:MM, если названо конкретное время, иначе пустая строка"},
                        "period": {"type": "string", "enum": ["today", "tomorrow", "week", "overdue", "all"]},
                        "instruction": {"type": "string", "description": "Для delegate: полное поручение ассистенту"},
                    },
                    "required": ["type"],
                },
            },
            "reply": {"type": "string", "description": "Короткий ответ, если действий нет или нужно уточнение"},
        },
        "required": ["actions"],
    },
}


def build_system(now: datetime, areas: list[str], tasks: list, history: list[str] | None = None,
                 day_start: int = 6) -> str:
    night = now.hour < day_start
    base = now.date()

    def label(i: int) -> str:
        if night:
            return " (сегодня = завтра: день после сна)" if i == 0 else " (послезавтра)" if i == 1 else ""
        return " (сегодня)" if i == 0 else " (завтра)" if i == 1 else " (послезавтра)" if i == 2 else ""

    days = "\n".join(
        f"{(base + timedelta(days=i)).isoformat()} — {WEEKDAYS[(base + timedelta(days=i)).weekday()]}{label(i)}"
        for i in range(15))
    night_rule = (
        f"\nСейчас ночь ({now:%H:%M}), пользователь ещё не ложился. Для него «сегодня» и «завтра» — это один и тот же "
        f"день: {base.isoformat()} ({WEEKDAYS[base.weekday()]}), день после сна. «Послезавтра» — следующий за ним.\n"
        if night else "")
    def tl(t):
        when = str(t['due_date'] or 'без срока')
        if t['remind_at']:
            when += " " + t['remind_at'].astimezone(now.tzinfo).strftime('%H:%M')
        return f"#{t['id']} | {t['title']} | {t['area'] or '-'} | {when}"
    task_lines = "\n".join(tl(t) for t in tasks[:150]) or "(задач нет)"
    hist = "\n".join(history or []) or "(нет)"
    return f"""Ты — служебный модуль, который разбирает сообщения в Telegram-боте задач и поручений (пользователю себя никак не называешь). Пользователь пишет коротко, по-русски, как в заметки, часто голосом.
Сейчас: {now.strftime('%Y-%m-%d %H:%M')}, {WEEKDAYS[now.weekday()]}.
{night_rule}
Календарь на ближайшие дни:
{days}

Сферы пользователя: {', '.join(areas)}

Открытые задачи:
{task_lines}

Предыдущие сообщения за последние часы и что по ним сделано (контекст; повторно не выполняй, если тебя прямо не просят повторить):
{hist}

Правила:
- Новая задача или несколько задач в одном сообщении → по action "add" на каждую.
- title: коротко и близко к словам пользователя, ничего не додумывай. Встреча, приём, созвон — так, как назвал пользователь («Барбер», «Эдгар, психолог», «Кофе с Серёгой в Факторе»); не превращай встречу в «созвониться», если про звонок не сказано. Дело — с глагола («Скинуть Кириллу условия по QQ»). Без даты и времени в title. Явные ошибки распознавания голоса исправляй («Барбар» → «Барбер»).
- area: выбери самую подходящую из списка сфер. EQLBM — клуб, обучение, игроки, комьюнити. Рейкбек — румы, аффилейт, агенты, выплаты. Сайт и контент — сайт, Instagram, посты, видео. Личное — всё остальное. Если сферы другие — ориентируйся по смыслу.
- due_date: если срок назван («завтра», «в пятницу», «до конца месяца» → последний день месяца) — дата YYYY-MM-DD. Нет срока — пустая строка.
- Слова «затем», «потом», «после этого», «после <предыдущая встреча>» без своей даты — это тот же день, что и в предыдущем сообщении.
- time: только если названо конкретное время («в 15:00», «в 3 дня» → 15:00, «вечером» без времени → пустая строка). Если время назвали без даты и без связи с предыдущим сообщением — ближайший такой момент в будущем.
- «Напомни через 2 часа» → due_date и time = сейчас + 2 часа.
- Сообщение о том, что задача сделана («сделал», «отправил», «готово») → "complete" с task_id подходящей открытой задачи.
- Просьба перенести/изменить задачу → "edit" с task_id и только изменёнными полями; неизменённые поля не передавай. Чтобы убрать срок или время, передай в due_date или time значение "none".
- «Перенеси на 19», «на 9», «на полвосьмого» — если у задачи есть время и не сказано «числа», месяца или дня недели, это ВРЕМЯ (19:00) того же дня, а не дата. Число вида «на 25-е», «на 19 октября», «на 19 число» — дата. Если действительно непонятно — переспроси в reply.
- Перенос — это всегда "edit" существующей задачи, никогда не новый "add".
- Просьба удалить → "delete".
- Вопрос о состоянии задачи («ты перенёс Эдгара?», «во сколько барбер?», «что стоит на завтра в 13?») → пустой actions и короткий ответ в reply по списку задач выше. Не выдавай список, если спросили про одну задачу.
- «В календаре стоит X», «у меня X в 14» — это встреча: "add" с датой и временем (бот сам свяжет её с событием в календаре, дубля не будет).
- Вопрос «что у меня…», «что по EQLBM», «что на неделе» → "list" с period и, если названа, area.
- Поручение, которое надо выполнить сейчас — найти, узнать, подобрать, сравнить, посчитать, написать текст, проверить почту или календарь, ответить на вопрос о мире («найди билеты в Дубай на конец ноября», «какие документы нужны для визы в ОАЭ», «напиши ответ Кириллу») → один "delegate" с instruction: поручение словами пользователя плюс нужный контекст. Продолжение недавнего поручения («а из Москвы?», «беру второй», «а подешевле?») — тоже "delegate". Но «до пятницы купить билеты» — это обычная задача "add" на будущее.
- Всё про CRM — игроки, ники, рейк, рейкбек, выплаты, сделки и румы, лиды, участники клуба и подписки, ученики, расходы, задачи помощника («сколько рейка у Шимано за сентябрь», «новый лид Иван из HH», «внеси рейк Пинкману 300 за октябрь», «кому выплатить рейкбек», «кому за какие ники выплатить рб за сентябрь», «поставь помощнику задачу…») → "delegate". Личные задачи без упоминания CRM-сущностей остаются обычными "add".
- Подтверждение или ответ на вопрос ассистента из предыдущих сообщений («да», «вноси», «да, всё верно», «замени», «прибавь», «нет, это Шимано») → "delegate" с instruction: что ответил пользователь и на что (кратко перескажи предложение ассистента).
- «Попробуй ещё», «повтори», «ещё раз», «давай снова» — повтори последнее невыполненное (или последнее) поручение из предыдущих сообщений тем же действием (для поручения — "delegate" с тем же instruction).
- Если сообщение начинается с [В ответ на сообщение: «…»], это ответ на то сообщение — используй его как контекст («Это» = то, что в цитате).
- Разговор, а не дело: вопросы о самом боте («как тебя зовут», «как бы ты назвалась», «что ты умеешь»), болтовня, мнения, благодарности, шутки, «как дела» → "delegate" с instruction = сообщение пользователя как есть. Сам в reply на такое не отвечай и не представляйся.
- В reply никогда не перечисляй задачи, если о них прямо не спросили. reply — только для коротких уточнений по задачам.
- Если не понятно, к какой задаче относится complete/edit/delete — не угадывай, верни пустой actions и короткий вопрос в reply.
Всегда отвечай вызовом apply_actions."""


class Parser:
    def __init__(self, api_key: str, model: str, day_start: int = 6):
        self.client = AsyncAnthropic(api_key=api_key)
        self.model = model
        self.day_start = day_start

    async def parse(self, text: str, now: datetime, areas: list[str], tasks: list,
                    history: list[str] | None = None) -> dict:
        msg = await self.client.messages.create(
            model=self.model,
            max_tokens=1024,
            system=build_system(now, areas, tasks, history, self.day_start),
            tools=[TOOL],
            tool_choice={"type": "tool", "name": "apply_actions"},
            messages=[{"role": "user", "content": text}],
        )
        for block in msg.content:
            if block.type == "tool_use":
                return block.input
        return {"actions": [], "reply": "Не понял, переформулируй, пожалуйста."}


async def transcribe(api_key: str, audio: bytes, filename: str = "voice.ogg") -> str:
    async with httpx.AsyncClient(timeout=60) as c:
        r = await c.post(
            "https://api.groq.com/openai/v1/audio/transcriptions",
            headers={"Authorization": f"Bearer {api_key}"},
            data={"model": "whisper-large-v3-turbo", "language": "ru", "response_format": "json"},
            files={"file": (filename, audio, "audio/ogg")},
        )
        r.raise_for_status()
        return r.json().get("text", "").strip()
